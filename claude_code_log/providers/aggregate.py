"""Rendering for the index that links provider-specific project indexes."""

import json
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, select_autoescape

from claude_code_log.cache import get_library_version
from claude_code_log.converter import get_index_filename
from claude_code_log.utils import atomic_write_text


def write_all_providers_index(
    output_root: Path,
    providers: list[dict[str, Any]],
    skipped: list[dict[str, str]],
    output_format: str = "html",
) -> Path:
    """Write a root index linking successfully rendered provider indexes.

    ``providers`` contains ``name``, ``index_path`` and ``session_count``.
    Paths are required to be inside ``output_root`` so the generated links stay
    relative and cannot escape the aggregate output directory.
    """
    rows: list[dict[str, Any]] = []
    resolved_output_root = output_root.resolve()
    for provider in providers:
        index_path = Path(provider["index_path"])
        try:
            href = index_path.resolve().relative_to(resolved_output_root).as_posix()
        except ValueError as exc:
            raise ValueError("provider index must be inside output_root") from exc
        rows.append(
            {
                "name": str(provider["name"]),
                "href": href,
                "session_count": int(provider["session_count"]),
            }
        )

    output_root.mkdir(parents=True, exist_ok=True)

    if output_format == "html":
        template_dir = Path(__file__).parents[1] / "html" / "templates"
        env = Environment(
            loader=FileSystemLoader(str(template_dir)),
            autoescape=select_autoescape(["html", "xml"]),
        )
        content = env.get_template("all_providers_index.html").render(
            providers=rows,
            skipped=skipped,
            library_version=get_library_version(),
        )
    elif output_format in ("md", "markdown"):
        lines = [
            f"<!-- Generated by claude-code-log v{get_library_version()} -->",
            "",
            "# All providers",
            "",
        ]
        lines.extend(
            f"- [{row['name']}]({row['href']}) — {row['session_count']} sessions discovered"
            for row in rows
        )
        if skipped:
            lines.extend(["", "## Not rendered", ""])
            lines.extend(f"- {item['name']}: {item['reason']}" for item in skipped)
        content = "\n".join(lines) + "\n"
    elif output_format == "json":
        content = (
            json.dumps(
                {
                    "version": get_library_version(),
                    "providers": rows,
                    "skipped": skipped,
                },
                indent=2,
            )
            + "\n"
        )
    else:
        raise ValueError(f"Unsupported all-providers format: {output_format}")

    index_path = output_root / get_index_filename(output_format)
    atomic_write_text(index_path, content)
    return index_path
