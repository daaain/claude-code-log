#!/usr/bin/env python3
"""Generate the minimal theme's dark Pygments sheet (``pygments_dark.css``).

The classic Pygments token colours (``components/pygments_styles.css``,
based on Pygments' ``default`` style) are tuned for a light background; on
the minimal theme's dark ``--code`` box several of them are illegible
(``.nf`` is pure blue, ``.nn`` too). This script emits Pygments'
``github-dark`` token colours, scoped to the minimal theme's two dark
selectors (work/minimal-theme-dag.md § 1.3)::

    @media (prefers-color-scheme: dark) {
        :root:not([data-theme="light"]) .theme-minimal .highlight .k { … }
    }
    :root[data-theme="dark"] .theme-minimal .highlight .k { … }

Light mode keeps the classic sheet untouched.

Because the dark rules are layered over the classic ones, each rule also
neutralises whatever the classic sheet sets on that token and github-dark
doesn't (``font-weight: bold`` on keywords, the red ``border`` on ``.err``,
…); otherwise light-theme styling would leak into dark. Token classes only
the classic sheet styles get the neutral reset alone.

The background is deliberately left out: the code box keeps the theme's
``--code`` token, and plain text inherits ``--fg``.

The output is committed; ``test/test_minimal_theme.py`` fails if it drifts
from what this script generates (e.g. after a Pygments upgrade changes
github-dark, or the classic sheet gains a token). Regenerate with::

    uv run python scripts/generate_minimal_pygments_css.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path
from typing import Any, cast

from pygments.formatters import HtmlFormatter

COMPONENTS = (
    Path(__file__).resolve().parent.parent
    / "claude_code_log"
    / "html"
    / "templates"
    / "components"
)
CLASSIC_SHEET = COMPONENTS / "pygments_styles.css"
OUTPUT = COMPONENTS / "minimal" / "pygments_dark.css"
STYLE = "github-dark"

# `.highlight .k { color: #FF7B72; font-weight: bold } /* Keyword */`
_TOKEN_RULE = re.compile(r"^\.highlight \.([\w-]+) \{\s*(.*?)\s*\}")

# The neutral value for each property the classic sheet may set, used when
# github-dark leaves that property alone on the same token.
_NEUTRAL = {
    "color": "inherit",
    "background-color": "transparent",
    "font-weight": "normal",
    "font-style": "normal",
    "border": "none",
    "text-decoration": "none",
}

DARK_SELECTORS = (
    ':root:not([data-theme="light"]) .theme-minimal',
    ':root[data-theme="dark"] .theme-minimal',
)


def _declarations(body: str) -> list[tuple[str, str]]:
    result: list[tuple[str, str]] = []
    for part in body.split(";"):
        if ":" not in part:
            continue
        name, value = part.split(":", 1)
        result.append((name.strip().lower(), value.strip()))
    return result


def _token_rules(css: str) -> dict[str, list[tuple[str, str]]]:
    """Token class → declarations, for the `.highlight .<token>` rules."""
    rules: dict[str, list[tuple[str, str]]] = {}
    for line in css.splitlines():
        match = _TOKEN_RULE.match(line.strip())
        if match:
            rules[match.group(1)] = _declarations(match.group(2))
    return rules


def _merged(
    classic: list[tuple[str, str]], dark: list[tuple[str, str]]
) -> list[tuple[str, str]]:
    dark_names = {name for name, _ in dark}
    resets = [
        (name, _NEUTRAL[name])
        for name, _ in classic
        if name not in dark_names and name in _NEUTRAL
    ]
    return resets + [(name, value.lower()) for name, value in dark]


def build_css() -> str:
    """The full text of pygments_dark.css."""
    classic = _token_rules(CLASSIC_SHEET.read_text(encoding="utf-8"))
    formatter = cast(Any, HtmlFormatter(style=STYLE))
    dark = _token_rules(formatter.get_style_defs(".highlight"))
    tokens = list(dark) + [token for token in classic if token not in dark]

    rules: list[str] = []
    for token in tokens:
        decls = _merged(classic.get(token, []), dark.get(token, []))
        if not decls:
            continue
        body = "; ".join(f"{name}: {value}" for name, value in decls)
        rules.append(f".highlight .{token} {{ {body} }}")

    media, forced = DARK_SELECTORS
    lines = [
        "/* GENERATED by scripts/generate_minimal_pygments_css.py - do not edit.",
        f"   Pygments '{STYLE}' token colours for the minimal theme in dark",
        "   mode; light mode keeps components/pygments_styles.css. Each rule",
        "   also neutralises what the classic sheet sets on the same token. */",
        "",
        "@media (prefers-color-scheme: dark) {",
    ]
    lines += [f"    {media} {rule}" for rule in rules]
    lines += ["}", ""]
    lines += [f"{forced} {rule}" for rule in rules]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    css = build_css()
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != css:
            print(f"{OUTPUT} is out of date; run {Path(__file__).name}")
            return 1
        return 0
    OUTPUT.write_text(css, encoding="utf-8")
    print(f"Wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
