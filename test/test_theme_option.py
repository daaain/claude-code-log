"""`--theme {classic,minimal,default}`: plumbing, staleness and precedence.

Themes share filenames (work/minimal-theme-dag.md § 7 decision 1): the
minimal theme overwrites combined_transcripts.html / session-*.html, and
the theme a page was written in is recorded in its generator stamp
(``<!-- Generated by claude-code-log vX theme=minimal -->``). These tests
pin that every path deciding regeneration reads that stamp — so switching
theme regenerates everything, switching back too, and nothing written in
one theme ever passes as current for the other — and that classic output
is byte-identical to what the renderer produced before themes existed.
"""

