@pytest.mark.tui
def test_tui_export_uses_theme(tmp_path: Path) -> None:
    from claude_code_log.tui import SessionBrowser

    project = _small_project(tmp_path)
    _convert(project, "classic")
    session_file = project / "session-test_session.html"
    assert check_html_theme(session_file) == "classic"

    app = SessionBrowser(project, html_theme="minimal")
    assert app.html_theme == "minimal"
    # Textual's own UI theme is untouched by the HTML theme.
    assert app.theme == "gruvbox"
    result = app._ensure_session_file("test_session", "html")
    assert result == session_file  # same filename, overwritten
    assert check_html_theme(session_file) == "minimal"

    classic_app = SessionBrowser(project)
    classic_app._ensure_session_file("test_session", "html")
    assert check_html_theme(session_file) == "classic"
