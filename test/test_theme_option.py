MULTI_SESSION_PROJECT = (
    TEST_DATA / "real_projects" / "-Users-dain-workspace-coderabbit-review-helper"
)
# Paginates MULTI_SESSION_PROJECT into two pages (see test_streaming_render).
PAGE_SIZE = 30


def _copy_project(dest_root: Path, source: Path = MULTI_SESSION_PROJECT) -> Path:
    work_dir = dest_root / source.name
    work_dir.parent.mkdir(parents=True, exist_ok=True)
    shutil.copytree(source, work_dir)
    return work_dir


def _small_project(tmp_path: Path) -> Path:
    project = tmp_path / "projects" / "-tmp-small"
    project.mkdir(parents=True)
    shutil.copy(REPRESENTATIVE, project / "test_session.jsonl")
    return project


def _convert(project: Path, theme: str, **kwargs: Any) -> RegenerationReport:
    report = RegenerationReport()
    kwargs.setdefault("page_size", PAGE_SIZE)
    convert_jsonl_to("html", project, silent=True, theme=theme, report=report, **kwargs)
    return report


def _html(project: Path) -> dict[str, bytes]:
    files = {p.name: p.read_bytes() for p in sorted(project.glob("*.html"))}
    assert files, "conversion produced no HTML files"
    return files


def _themes_on_disk(project: Path) -> set[str]:
    return {str(check_html_theme(p)) for p in project.glob("*.html")}


