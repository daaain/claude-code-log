class TestRendering:
    def test_classic_is_byte_identical_to_unthemed(self) -> None:
        messages = load_transcript(REPRESENTATIVE, silent=True)
        unthemed = generate_html(messages, "T")
        assert generate_html(messages, "T", theme="classic") == unthemed
        assert generate_html(messages, "T", theme="default") == unthemed
        # The classic stamp is the bare version, exactly as before themes.
        assert (
            f"<!-- Generated by claude-code-log v{get_library_version()} -->\n"
            in unthemed
        )
        assert "theme-minimal" not in unthemed
        assert "theme=" not in unthemed.split("\n", 2)[1]

    def test_minimal_render_marks_body_and_stamp(self, tmp_path: Path) -> None:
        messages = load_transcript(REPRESENTATIVE, silent=True)
        html = generate_html(messages, "T", theme="minimal")
        assert "<body class='theme-minimal'>" in html
        assert html.split("\n", 2)[1] == (
            f"<!-- Generated by claude-code-log v{get_library_version()} "
            "theme=minimal -->"
        )
        page = tmp_path / "page.html"
        page.write_text(html, encoding="utf-8")
        # What the staleness checks read back is exactly the expected stamp.
        assert check_html_version(page) == html_generator_stamp("minimal")
        assert check_html_theme(page) == "minimal"
        assert not is_html_outdated(page, "minimal")
        assert is_html_outdated(page, "classic")
        assert is_html_outdated(page)  # built-in default is classic

    def test_minimal_keeps_every_card_hook(self) -> None:
        """The minimal page restyles cards but keeps what scripts key on.

        Filter, timeline, search, fold bars and live update read card
        classes, ids, uuids and `.timestamp[data-timestamp]`; the theme
        only adds gutter spans inside the header (P3a), so all of those
        must match the classic page card for card.
        """
        import re

        messages = load_transcript(REPRESENTATIVE, silent=True)
        classic = generate_html(messages, "T", theme="classic")
        minimal = generate_html(messages, "T", theme="minimal")

        card = re.compile(r"<div class='message ([^']*)'([^>]*)>")
        # P5 adds the lane model as double-quoted `data-lane*` / `data-spawns`
        # / `data-merges` / `data-teammate-*` attributes; everything else on
        # the card is the classic markup.
        lane_attr = re.compile(r' data-(?:lane|spawns|merges|teammate)[\w-]*="[^"]*"')
        stripped = [(c, lane_attr.sub("", rest)) for c, rest in card.findall(minimal)]
        assert stripped == card.findall(classic)
        assert all(' data-lane="' in rest for _c, rest in card.findall(minimal))
        stamp = re.compile(r"<span class='timestamp'[^>]*>[^<]*</span>")
        assert stamp.findall(minimal) == stamp.findall(classic)
        fold = re.compile(r"<div class='fold-bar-section[^>]*>")
        assert fold.findall(minimal) == fold.findall(classic)
        for marker in ('<div id="transcript">', '<div class="filter-toolbar">'):
            assert minimal.count(marker) == classic.count(marker) == 1
        # The classic floating stack moves into the toolbar: same ids, once.
        for control in (
            "filterMessages",
            "toggleTimeline",
            "followUpdates",
            "resumeSession",
            "toggleDetails",
            "toggleUserView",
            "toggleDebug",
        ):
            assert minimal.count(f'id="{control}"') == 1, control
            assert classic.count(f'id="{control}"') == 1, control
        assert minimal.index("<nav class='mn-toolbar'") < minimal.index(
            'id="filterMessages"'
        )

    def test_classic_page_is_stale_when_the_default_changes(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        """An archive built with `default` regenerates if the default moves."""
        messages = load_transcript(REPRESENTATIVE, silent=True)
        page = tmp_path / "page.html"
        page.write_text(generate_html(messages, "T", theme="default"), encoding="utf-8")
        assert not is_html_outdated(page, "default")
        monkeypatch.setattr(utils, "DEFAULT_THEME", "minimal")
        assert is_html_outdated(page, "default")


