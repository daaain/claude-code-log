class TestThemeSwitchRegenerates:
    def test_single_file_project_round_trip(self, tmp_path: Path) -> None:
        project = _small_project(tmp_path)
        first = _convert(project, "classic")
        assert first.combined_regenerated and first.sessions_regenerated == 1
        classic_files = _html(project)
        assert set(classic_files) == {
            "combined_transcripts.html",
            "session-test_session.html",
        }

        # Same theme again: nothing to do.
        again = _convert(project, "classic")
        assert not again.combined_regenerated and again.sessions_regenerated == 0

        # Switch: every output rewritten in place, same filenames.
        switched = _convert(project, "minimal")
        assert switched.combined_regenerated and switched.sessions_regenerated == 1
        assert set(_html(project)) == set(classic_files)
        assert _themes_on_disk(project) == {"minimal"}

        steady = _convert(project, "minimal")
        assert not steady.combined_regenerated and steady.sessions_regenerated == 0

        # Switch back: regenerated, and byte-identical to the first run.
        back = _convert(project, "default")
        assert back.combined_regenerated and back.sessions_regenerated == 1
        assert _html(project) == classic_files

    def test_paginated_round_trip(self, tmp_path: Path) -> None:
        project = _copy_project(tmp_path)
        _convert(project, "classic")
        classic_files = _html(project)
        assert "combined_transcripts_2.html" in classic_files

        switched = _convert(project, "minimal")
        assert switched.combined_regenerated
        assert switched.sessions_regenerated == len(
            [n for n in classic_files if n.startswith("session-")]
        )
        assert set(_html(project)) == set(classic_files)
        assert _themes_on_disk(project) == {"minimal"}

        steady = _convert(project, "minimal")
        assert not steady.combined_regenerated and steady.sessions_regenerated == 0

        _convert(project, "classic")
        assert _html(project) == classic_files

    def test_streaming_path_reads_the_theme(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        project = _copy_project(tmp_path)
        _convert(project, "classic")
        classic_files = _html(project)

        monkeypatch.setenv("CLAUDE_CODE_LOG_STREAMING", "1")
        streamed: list[str] = []
        real = converter._stream_paginated_conversion

        def spy(*args: Any, **kwargs: Any) -> Any:
            streamed.append(kwargs["theme"])
            return real(*args, **kwargs)

        monkeypatch.setattr(converter, "_stream_paginated_conversion", spy)

        def no_full_load(*args: Any, **kwargs: Any) -> Any:
            raise AssertionError("expected the streamed path, not a full load")

        # The cache is fresh, so a streamed pass never needs the full loader.
        monkeypatch.setattr(converter, "load_directory_transcripts", no_full_load)

        report = _convert(project, "minimal")
        assert streamed == ["minimal"]
        assert report.combined_regenerated
        assert _themes_on_disk(project) == {"minimal"}

        _convert(project, "classic")
        assert _html(project) == classic_files

    def test_session_scoped_path_reads_the_theme(self, tmp_path: Path) -> None:
        """`--combined no` (watch's default) regenerates sessions per theme…

        …and rewrites a combined output left in the other theme, because the
        session pages link back to it (no mixed-theme archive).
        """
        project = _copy_project(tmp_path)
        _convert(project, "classic")
        classic_files = _html(project)

        report = _convert(project, "minimal", write_combined=False)
        assert report.combined_regenerated, "combined left in the old theme"
        assert report.sessions_regenerated > 0
        assert _themes_on_disk(project) == {"minimal"}

        # Now consistent: a further --combined no tick does nothing.
        steady = _convert(project, "minimal", write_combined=False)
        assert not steady.combined_regenerated and steady.sessions_regenerated == 0

        _convert(project, "classic", write_combined=False)
        assert _html(project) == classic_files

    def test_combined_no_without_combined_output_stays_combined_free(
        self, tmp_path: Path
    ) -> None:
        project = _small_project(tmp_path)
        _convert(project, "classic", write_combined=False)
        assert not (project / "combined_transcripts.html").exists()
        _convert(project, "minimal", write_combined=False)
        assert not (project / "combined_transcripts.html").exists()
        assert _themes_on_disk(project) == {"minimal"}

    def test_render_pool_carries_the_theme(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        monkeypatch.setattr(render_dispatch, "_MIN_MESSAGES_FOR_RENDER_POOL", 0)
        monkeypatch.setattr(render_dispatch, "_MIN_ENTRIES_FOR_RENDER_POOL", 0)
        monkeypatch.setattr(
            render_pool_module, "available_memory_bytes", lambda: 64 * 1024**3
        )
        dispatched: list[RenderUnit] = []
        original_submit = RenderPool.submit

        def counting_submit(self: RenderPool, unit: RenderUnit) -> Any:
            future = original_submit(self, unit)
            if future is not None:
                dispatched.append(unit)
            return future

        monkeypatch.setattr(RenderPool, "submit", counting_submit)

        project = _copy_project(tmp_path)
        _convert(project, "minimal", render_jobs=2)
        kinds = {unit.kind for unit in dispatched}
        assert kinds == {"page", "session"}, "the pool never rendered"
        assert _themes_on_disk(project) == {"minimal"}

        steady = _convert(project, "minimal", render_jobs=2)
        assert not steady.combined_regenerated and steady.sessions_regenerated == 0

    def test_projects_hierarchy(self, tmp_path: Path) -> None:
        projects = tmp_path / "projects"
        project = _copy_project(projects)
        process_projects_hierarchy(projects, theme="classic", page_size=PAGE_SIZE)
        classic_files = _html(project)

        process_projects_hierarchy(projects, theme="minimal", page_size=PAGE_SIZE)
        assert set(_html(project)) == set(classic_files)
        assert _themes_on_disk(project) == {"minimal"}
        assert (projects / "index.html").exists()

        # A second minimal pass plans the project as current.
        mtimes = {p.name: p.stat().st_mtime_ns for p in project.glob("*.html")}
        process_projects_hierarchy(projects, theme="minimal", page_size=PAGE_SIZE)
        assert {p.name: p.stat().st_mtime_ns for p in project.glob("*.html")} == mtimes

        process_projects_hierarchy(projects, theme="default", page_size=PAGE_SIZE)
        assert _html(project) == classic_files

    def test_hierarchy_watch_shape_rewrites_stale_theme_combined(
        self, tmp_path: Path
    ) -> None:
        """serve --watch / watch --all-projects tick: --combined no."""
        projects = tmp_path / "projects"
        project = _copy_project(projects)
        process_projects_hierarchy(projects, theme="classic", page_size=PAGE_SIZE)
        process_projects_hierarchy(
            projects, theme="minimal", page_size=PAGE_SIZE, write_combined=False
        )
        assert _themes_on_disk(project) == {"minimal"}


