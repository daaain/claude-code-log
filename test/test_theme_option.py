class TestCli:
    def test_precedence_flag_env_default(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.delenv(THEME_ENV_VAR, raising=False)
        assert _resolve_theme(None) == DEFAULT_THEME
        monkeypatch.setenv(THEME_ENV_VAR, "minimal")
        assert _resolve_theme(None) == "minimal"
        # An explicit flag always wins — `default` and `classic` included.
        assert _resolve_theme("classic") == "classic"
        assert _resolve_theme("default") == DEFAULT_THEME
        monkeypatch.setenv(THEME_ENV_VAR, "default")
        assert _resolve_theme(None) == DEFAULT_THEME
        assert _resolve_theme("minimal") == "minimal"
        monkeypatch.setenv(THEME_ENV_VAR, "")
        assert _resolve_theme(None) == DEFAULT_THEME

    def _capture_convert(self, monkeypatch: pytest.MonkeyPatch) -> list[str]:
        seen: list[str] = []

        def fake_convert(*args: Any, **kwargs: Any) -> Path:
            seen.append(kwargs["theme"])
            return Path("out.html")

        monkeypatch.setattr("claude_code_log.cli.convert_jsonl_to", fake_convert)
        return seen

    def test_convert_env_and_flag(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        project = _small_project(tmp_path)
        seen = self._capture_convert(monkeypatch)
        runner = CliRunner()
        monkeypatch.delenv(THEME_ENV_VAR, raising=False)
        assert runner.invoke(main, [str(project)]).exit_code == 0
        monkeypatch.setenv(THEME_ENV_VAR, "minimal")
        assert runner.invoke(main, [str(project)]).exit_code == 0
        assert runner.invoke(main, [str(project), "--theme", "classic"]).exit_code == 0
        assert runner.invoke(main, [str(project), "--theme", "default"]).exit_code == 0
        assert seen == ["classic", "minimal", "classic", DEFAULT_THEME]

    def test_unknown_env_value_is_a_usage_error(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        project = _small_project(tmp_path)
        seen = self._capture_convert(monkeypatch)
        monkeypatch.setenv(THEME_ENV_VAR, "dark")
        result = CliRunner().invoke(main, [str(project)])
        assert result.exit_code == 2
        assert THEME_ENV_VAR in result.output
        assert "classic" in result.output and "minimal" in result.output
        assert seen == []
        # An explicit flag doesn't consult the environment at all.
        ok = CliRunner().invoke(main, [str(project), "--theme", "minimal"])
        assert ok.exit_code == 0 and seen == ["minimal"]

    def test_unknown_flag_value_rejected(self, tmp_path: Path) -> None:
        result = CliRunner().invoke(
            main, [str(_small_project(tmp_path)), "--theme", "dark"]
        )
        assert result.exit_code == 2

    def test_theme_with_markdown_warns(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        project = _small_project(tmp_path)
        self._capture_convert(monkeypatch)
        result = CliRunner().invoke(
            main, [str(project), "--theme", "minimal", "--format", "md"]
        )
        assert result.exit_code == 0
        assert "--theme is HTML-only" in result.output

    def test_real_conversion_via_env(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        project = _small_project(tmp_path)
        monkeypatch.setenv(THEME_ENV_VAR, "minimal")
        assert CliRunner().invoke(main, [str(project)]).exit_code == 0
        assert _themes_on_disk(project) == {"minimal"}
        assert (
            CliRunner().invoke(main, [str(project), "--theme", "classic"]).exit_code
            == 0
        )
        assert _themes_on_disk(project) == {"classic"}

    @pytest.mark.parametrize("command", ["serve", "watch"])
    def test_serve_and_watch_accept_theme(self, command: str) -> None:
        result = CliRunner().invoke(main, [command, "--help"])
        assert result.exit_code == 0
        assert "--theme" in result.output
        assert THEME_ENV_VAR in result.output

    def test_watch_passes_theme(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        project = _small_project(tmp_path)
        seen = self._capture_convert(monkeypatch)

        class _Engine:
            def __init__(self, *args: Any, **kwargs: Any) -> None:
                self.stats = type("S", (), {"conversions": 0, "polls": 0, "errors": 0})

            def prime(self) -> None:
                pass

            def run(self) -> None:
                pass

        monkeypatch.setattr("claude_code_log.watch.WatchEngine", _Engine)
        monkeypatch.setenv(THEME_ENV_VAR, "minimal")
        result = CliRunner().invoke(main, ["watch", str(project)])
        assert result.exit_code == 0, result.output
        result = CliRunner().invoke(main, ["watch", str(project), "--theme", "classic"])
        assert result.exit_code == 0, result.output
        assert seen == ["minimal", "classic"]

    def test_serve_passes_theme(
        self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch
    ) -> None:
        seen: list[str] = []

        def fake_hierarchy(*args: Any, **kwargs: Any) -> Path:
            seen.append(kwargs["theme"])
            raise SystemExit(0)  # stop before the server starts

        monkeypatch.setattr(
            "claude_code_log.cli.process_projects_hierarchy", fake_hierarchy
        )
        monkeypatch.setenv(THEME_ENV_VAR, "minimal")
        projects = tmp_path / "projects"
        projects.mkdir()
        CliRunner().invoke(main, ["serve", "--projects-dir", str(projects)])
        CliRunner().invoke(
            main, ["serve", "--projects-dir", str(projects), "--theme", "default"]
        )
        assert seen == ["minimal", DEFAULT_THEME]


