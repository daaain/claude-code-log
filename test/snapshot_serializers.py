"""Custom syrupy serializers for HTML and Markdown snapshot testing."""

import re
from typing import Any

from syrupy.extensions.amber import AmberSnapshotExtension
from syrupy.types import SerializableData

# Shared normalisation patterns (used by both HTML and Markdown serializers)
# Library version comment - changes between releases
_VERSION_PATTERN = r"<!-- Generated by claude-code-log v[\d.]+(-\w+)? -->"
_VERSION_REPLACEMENT = "<!-- Generated by claude-code-log v[VERSION] -->"

# Pytest tmp paths - varies per test run
# Handles: /tmp/pytest-123/..., /private/var/folders/.../tmp/pytest-123/...
_TMP_PATH_PATTERN = (
    r"(/private)?(/var/folders/[^/]+/[^/]+/[^/]+/)?/tmp/pytest-[^\s\"'<>]+"
)
_TMP_PATH_REPLACEMENT = "/[TMP_PATH]"

# Inlined vis-timeline library (issue #278). On the no-output-directory
# render path the ~530 KB vendored JS/CSS is embedded directly in the page.
# That bulk is a third-party asset, not transcript-rendering output, so
# collapse it to a placeholder — otherwise every vis-timeline upgrade would
# rewrite megabytes of snapshot and drown real diffs. The presence of the
# tags (verified in browser/render tests) is what matters here, not bytes.
_INLINE_VIS_JS_PATTERN = r'<script id="vis-timeline-inline-js">.*?</script>'
_INLINE_VIS_CSS_PATTERN = r'<style id="vis-timeline-inline-css">.*?</style>'
_INLINE_VIS_JS_REPLACEMENT = (
    '<script id="vis-timeline-inline-js">[VIS_TIMELINE_JS]</script>'
)
_INLINE_VIS_CSS_REPLACEMENT = (
    '<style id="vis-timeline-inline-css">[VIS_TIMELINE_CSS]</style>'
)


class NormalisedMarkdownSerializer(AmberSnapshotExtension):
    """
    Custom serializer that normalises dynamic content in Markdown output.

    Normalises only truly dynamic content:
    - Library version comments (changes between releases)
    - Pytest tmp paths (varies per test run)
    """

    @classmethod
    def serialize(cls, data: SerializableData, **kwargs: Any) -> str:
        if isinstance(data, str):
            normalised = cls._normalise_markdown(data)
            return normalised
        return str(super().serialize(data, **kwargs))

    @classmethod
    def _normalise_markdown(cls, md: str) -> str:
        """Apply normalisation rules to Markdown content."""
        md = re.sub(_VERSION_PATTERN, _VERSION_REPLACEMENT, md)
        md = re.sub(_TMP_PATH_PATTERN, _TMP_PATH_REPLACEMENT, md)
        return md


class NormalisedHTMLSerializer(AmberSnapshotExtension):
    """
    Custom serializer that normalises dynamic content in HTML output.

    Normalises only truly dynamic content:
    - Library version comments (changes between releases)
    - Pytest tmp paths (varies per test run)

    Note: Timestamps, UUIDs, message IDs, token counts etc. come from the
    source JSONL test fixtures which are committed and static - no normalisation needed.
    """

    @classmethod
    def serialize(cls, data: SerializableData, **kwargs: Any) -> str:
        if isinstance(data, str):
            normalised = cls._normalise_html(data)
            return normalised
        return str(super().serialize(data, **kwargs))

    @classmethod
    def _normalise_html(cls, html: str) -> str:
        """Apply normalisation rules to HTML content."""
        html = re.sub(_VERSION_PATTERN, _VERSION_REPLACEMENT, html)
        html = re.sub(_TMP_PATH_PATTERN, _TMP_PATH_REPLACEMENT, html)

        # Last modified timestamps in project index (timezone-dependent)
        # 🕒 2023-11-14 23:15:00 -> 🕒 [LAST_MODIFIED]
        # These come from datetime.fromtimestamp() which uses local timezone
        html = re.sub(
            r"🕒 \d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}</div>",
            "🕒 [LAST_MODIFIED]</div>",
            html,
        )

        # Collapse the inlined vis-timeline library (issue #278) so its
        # ~530 KB of third-party bytes don't bloat or churn the snapshots.
        html = re.sub(
            _INLINE_VIS_JS_PATTERN,
            _INLINE_VIS_JS_REPLACEMENT,
            html,
            flags=re.DOTALL,
        )
        html = re.sub(
            _INLINE_VIS_CSS_PATTERN,
            _INLINE_VIS_CSS_REPLACEMENT,
            html,
            flags=re.DOTALL,
        )

        return html
